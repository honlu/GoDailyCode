package lcr132

func cuttingBamboo(bamboo_len int) int {
	const mod int64 = 1000000007
	/*
		核心思路：贪心 + 取模
		LCR 131 可以使用 DP：
			dp[i] = 长度为 i 的竹子切分后的最大乘积

		但本题 bamboo_len 较大，最大乘积会非常大，可能溢出。
		虽然题目要求最终结果对 1e9+7 取模，但不能在 DP 中
		一边取模一边比较最大值。
		例如：
			a = 1000000008
			b = 100
			真实大小：a > b
			取模后：
			a % MOD = 1
			b % MOD = 100
			此时反而变成 1 < 100，大小关系被破坏。
		因此本题不能直接沿用 LCR 131 的 DP + max，
		而是利用数学规律：尽可能把竹子切成长度 3。
	*/
	// 题目要求至少切一刀。
	//
	// 长度 2：
	// 2 = 1 + 1
	// 最大乘积 = 1 × 1 = 1
	if bamboo_len == 2 {
		return 1
	}
	// 长度 3：
	// 3 = 1 + 2
	// 最大乘积 = 1 × 2 = 2
	if bamboo_len == 3 {
		return 2
	}
	/*
		为什么优先切长度 3？
		对于长度 n >= 5：
			3 × (n - 3) > n
		也就是说，把长度 n 拆出一个 3，
		剩余 n-3，相比完全不拆，乘积会变得更大。
		例如：
			5 → 3 × 2 = 6
			6 → 3 × 3 = 9
			7 → 3 × 4 = 12
		继续推导可以得到：
			为了让乘积最大，应该尽可能多地切出长度 3。
	*/
	n := bamboo_len
	var ans int64 = 1
	/*
		为什么循环条件是 n > 4，而不是 n >= 3？
		因为最后需要刻意保留 2、3、4：
			n = 2：
				直接 ×2
			n = 3：
				直接 ×3
			n = 4：
				不能继续拆成 3+1，
				因为 3×1 = 3 < 2×2 = 4
				所以 4 应该看成：
				4 = 2 + 2
				乘积 = 4
		尤其需要避免最后剩下 1。
		例如 n = 10：
			错误：
				10 = 3 + 3 + 3 + 1
				乘积 = 3×3×3×1 = 27
			正确：
				10 = 3 + 3 + 4
				   = 3 + 3 + 2 + 2
				乘积 = 3×3×2×2 = 36
		因此：
			只要剩余长度 > 4，就继续切 3；
			剩下 2、3、4 时停止。
	*/
	for n > 4 {
		// 每切出一段长度 3，乘积就乘以 3。
		//
		// 根据模运算乘法性质：
		// (a * b) % MOD
		// = ((a % MOD) * (b % MOD)) % MOD
		//
		// 因此这里可以每一步取模，避免数值过大。
		ans = ans * 3 % mod
		// 已经切掉一段长度为 3 的竹子。
		n -= 3
	}
	/*
		循环结束后，n 只可能是 2、3、4：
			n == 2：
				ans × 2
			n == 3：
				ans × 3
			n == 4：
				ans × 4
				实际上代表最后拆成 2 × 2
		最后再进行一次取模。
	*/
	ans = ans * int64(n) % mod
	return int(ans)
}
